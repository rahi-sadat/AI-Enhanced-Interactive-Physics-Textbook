"""Capture portable package pins without copying .venv or local editable paths."""
import importlib.metadata as metadata
import json
from pathlib import Path
import platform
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def main():
    packages = {d.metadata['Name']: d.version for d in metadata.distributions()}
    sam_commit = subprocess.check_output(['git', '-C', str(ROOT/'sam2'), 'rev-parse', 'HEAD'], text=True).strip()
    snapshot = dict(python=platform.python_version(), platform=platform.platform(),
                    packages=dict(sorted(packages.items(), key=lambda item: item[0].lower())),
                    sam2=dict(repository='https://github.com/facebookresearch/sam2.git', commit=sam_commit),
                    torch_index='https://download.pytorch.org/whl/cu130',
                    known_packaging_warning='easyocr 1.7.2 requires opencv-python-headless, which is not installed.')
    folder = ROOT/'requirements'
    folder.mkdir(exist_ok=True)
    (folder/'windows-py313-environment.json').write_text(json.dumps(snapshot, indent=2)+'\n', encoding='utf-8')
    lines = ['# Generated by scripts/export_environment_snapshot.py; Windows x64, Python 3.13.',
             '# Install with --no-deps: every installed package is explicitly pinned.',
             '# SAM-2 is installed separately from the pinned source commit in the JSON snapshot.',
             '# The original GUI OpenCV/EasyOCR metadata warning is documented in WINDOWS_REPRODUCIBLE_SETUP.md.',
             '--extra-index-url https://download.pytorch.org/whl/cu130']
    lines.extend(f'{name}=={version}' for name, version in snapshot['packages'].items()
                 if name.lower().replace('_', '-') != 'sam-2')
    (folder/'windows-py313.lock.txt').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print(f'Captured {len(packages)} package versions; SAM-2 source commit {sam_commit}.')


if __name__ == '__main__':
    main()
